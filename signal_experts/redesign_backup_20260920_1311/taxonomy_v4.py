TARGET = {
    "PRESSURE": dict(ops=["T2_CHAIN"],
                     logic="否认结果+推责+期望压力（严厉）→ 逼模型把活重做一遍 → 应在“必须自己一步步推/算”的题上收益最大"),
    "CRITICAL": dict(ops=["T6_VERIFY"],
                     logic="判定为不合格且不解释原因 → 逼它重组/自查 → 应在“要查错、要重组”的题上收益最大"),
    "HEURISTIC": dict(ops=["T8_EXPLORE", "T9_REFRAME"],
                      logic="表达自己的怀疑+中立+不给提示 → 逼它自主探索多路径 → 应在“无唯一解/需换路子”的题上收益最大"),
    "ENCOURAGE": dict(ops=["T8_EXPLORE", "T11_SUSTAIN"],
                      logic="认可已有努力与优点 → 促使在原有思路上继续展开、写更多 → 应在“要展开、要写长”的题上有效"),
    "MISLEADING": dict(ops=["T7_RESIST"],
                       logic="自信而权威的错误线索 → 检验能否坚持正确方向 → 应在“抗扰判断”类题上损失最大（被带走）"),
}

_LINES = "\n".join([f"- {i} = {DESC[i]}" for i in IDS])

